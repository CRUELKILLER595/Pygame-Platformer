"""Load saved level JSON into runtime game objects."""

import json

from ..settings import TILE_SIZE
from ..objects.player import Player
from ..objects.Block import Block
from ..objects.fire import Fire
from ..objects.checkpoint import Checkpoint
from ..objects.start import Start
from ..objects.end import End
from ..objects.object import Object
from ..objects.fruit import Fruit
from ..objects.enemy import Enemy
from ..objects.trap import Trap
from ..objects.boxes import Box

from .character_registry import DEFAULT_CHARACTER
from .collision_profiles import make_collision_rect
from pixelbound_core.assets.asset_profiles import place_rect_in_cell


# IDs generated by the older filename-based enemy loader. These aliases keep
# already-saved levels working after switching to canonical registry IDs.
LEGACY_ENEMY_ASSET_IDS = {
    "enemy_fro_green": "enemy_frog_green",
    "enemy_fro_orange": "enemy_frog_orange",
    "enemy_fro_red": "enemy_frog_red",
    "enemy_she_blue": "enemy_sheep_blue",
    "enemy_she_green": "enemy_sheep_green",
    "enemy_she_red": "enemy_sheep_red",
    "enemy_she_yellow": "enemy_sheep_yellow",
    "enemy_tur_blue": "enemy_turtle_blue",
    "enemy_tur_green": "enemy_turtle_green",
    "enemy_tur_red": "enemy_turtle_red",
    "enemy_tur_yellow": "enemy_turtle_yellow",
}


class LevelManager:
    def __init__(self, asset_manager):
        self.asset_manager = asset_manager

    def load_level(self, level_path, character_id=DEFAULT_CHARACTER):
        # --------------------------------------------------
        # LOAD LEVEL JSON
        # --------------------------------------------------
        with open(level_path, "r", encoding="utf-8") as file:
            level_data = json.load(file)

        if not isinstance(level_data, dict):
            raise ValueError(f"Level file must contain a JSON object: {level_path}")

        objects = []
        player = None

        # --------------------------------------------------
        # COLLECT FRUIT REWARD ASSETS
        # --------------------------------------------------
        fruit_assets = [
            fruit_asset
            for fruit_asset in self.asset_manager.get_by_category("COLLECTIBLES")
            if fruit_asset.object_class is Fruit
        ]

        print("Available fruit rewards:", [asset.name for asset in fruit_assets])
        if not fruit_assets:
            print("WARNING: No fruit assets found. Boxes cannot spawn fruit rewards.")

        # --------------------------------------------------
        # LOAD LEVEL OBJECTS
        # --------------------------------------------------
        for index, data in enumerate(level_data.get("objects", [])):
            if not isinstance(data, dict):
                print("WARNING: Skipping malformed level object at index:", index)
                continue

            asset_id = data.get("id")
            if not isinstance(asset_id, str) or not asset_id:
                print("WARNING: Level object has no valid asset ID at index:", index)
                continue

            try:
                grid_x = int(data["x"])
                grid_y = int(data["y"])
            except (KeyError, TypeError, ValueError):
                print("WARNING: Invalid grid coordinates for asset:", asset_id)
                continue

            x = grid_x * TILE_SIZE
            y = grid_y * TILE_SIZE

            asset = self.asset_manager.get(asset_id)
            if asset is None:
                canonical_id = LEGACY_ENEMY_ASSET_IDS.get(asset_id)
                if canonical_id:
                    asset = self.asset_manager.get(canonical_id)
                    if asset is not None:
                        print(
                            "INFO: Migrated legacy enemy ID",
                            asset_id,
                            "->",
                            canonical_id,
                        )

            if asset is None:
                print("WARNING: Asset not found:", asset_id)
                continue

            # --------------------------------------------------
            # PLAYER — only one playable player is allowed.
            # --------------------------------------------------
            if asset.object_class == Player:
                if player is not None:
                    print(
                        "WARNING: Extra player spawn ignored:",
                        asset_id,
                        "at",
                        (grid_x, grid_y),
                    )
                    continue

                player = Player(
                    x,
                    y,
                    asset.width,
                    asset.height,
                    character_id=character_id,
                )
                continue

            # --------------------------------------------------
            # SOLID BLOCKS
            # --------------------------------------------------
            if asset.object_class == Block:
                obj = Block(x, y, asset.width, asset.image)

            # --------------------------------------------------
            # FIRE
            # --------------------------------------------------
            elif asset.object_class == Fire:
                obj = Fire(x, y, asset.width, asset.height)
                obj.on()

            # --------------------------------------------------
            # CHECKPOINTS
            # --------------------------------------------------
            elif asset.object_class == Checkpoint:
                obj = Checkpoint(x, y, asset.width, asset.height)

            # --------------------------------------------------
            # BREAKABLE BOXES
            # --------------------------------------------------
            elif asset.object_class == Box:
                obj = Box(x, y, asset, fruit_assets=fruit_assets)
                obj.profile = getattr(asset, "profile", {}) or {}
                collision_config = obj.profile.get("collision", {})
                obj.collision_type = collision_config.get("type", "solid")

                place_rect_in_cell(
                    obj.rect,
                    x,
                    y,
                    TILE_SIZE,
                    obj.profile.get("anchor", "bottom_center"),
                )
                collision_box = collision_config.get("box")
                if collision_box:
                    obj.collision_rect = make_collision_rect(
                        obj.rect,
                        collision_box,
                    )
                    obj.hitbox = obj.collision_rect

            # --------------------------------------------------
            # START
            # --------------------------------------------------
            elif asset.object_class == Start:
                obj = Start(x, y, asset.width, asset.height)

            # --------------------------------------------------
            # END
            # --------------------------------------------------
            elif asset.object_class == End:
                pressed_image = getattr(asset, "pressed_image", asset.image)
                obj = End(x, y, asset.image, pressed_image)

            # --------------------------------------------------
            # TRAPS
            # --------------------------------------------------
            elif asset.category == "TRAPS":
                obj = Trap(
                    x,
                    y,
                    asset.width,
                    asset.height,
                    asset=asset,
                )

                # Apply the same named anchor the editor uses.
                profile = getattr(asset, "profile", {}) or {}
                place_rect_in_cell(
                    obj.rect,
                    x,
                    y,
                    TILE_SIZE,
                    profile.get("anchor", "bottom_center"),
                )

                # Refresh the configured collision rectangle after anchoring.
                obj.collision_rect = make_collision_rect(
                    obj.rect,
                    obj.collision_profile,
                )
                obj.hitbox = obj.collision_rect

            # --------------------------------------------------
            # ENEMIES
            # Use the category as a fallback for older assets that were
            # registered with object_class=None.
            # --------------------------------------------------
            elif asset.object_class == Enemy or asset.category == "ENEMIES":
                profile = getattr(asset, "profile", {}) or {}
                collision_box = profile.get("collision", {}).get("box")
                obj = Enemy(
                    x,
                    y,
                    asset.width,
                    asset.height,
                    collision_profile=collision_box,
                    asset=asset,
                )
                original_x = obj.rect.x
                place_rect_in_cell(
                    obj.rect,
                    x,
                    y,
                    TILE_SIZE,
                    profile.get("anchor", "bottom_center"),
                )
                # Keep the patrol simulation's world bounds in sync with the
                # anchor-adjusted visual rectangle, otherwise the first loop
                # would snap an oversized enemy back to its old x-coordinate.
                anchor_delta_x = obj.rect.x - original_x
                obj.world_x = float(obj.rect.x)
                obj.left_bound += anchor_delta_x
                obj.right_bound += anchor_delta_x

                obj.collision_rect = make_collision_rect(
                    obj.rect,
                    obj.collision_profile,
                )
                obj.hitbox = obj.collision_rect

            # --------------------------------------------------
            # FRUITS / COLLECTIBLES
            # --------------------------------------------------
            elif asset.object_class == Fruit:
                obj = Fruit(x, y, asset, asset.name)

            # --------------------------------------------------
            # GENERIC OBJECT
            # --------------------------------------------------
            elif asset.object_class == Object:
                obj = Object(x, y, asset.width, asset.height, asset.name)

            # --------------------------------------------------
            # UNKNOWN ASSET
            # --------------------------------------------------
            else:
                print(
                    "WARNING: Unknown object class:",
                    asset.object_class,
                    "for asset:",
                    asset.name,
                )
                continue

            # Each runtime object is appended exactly once.
            objects.append(obj)

        # --------------------------------------------------
        # VALIDATE PLAYER
        # --------------------------------------------------
        if player is None:
            print("WARNING: Level has no player spawn!")

        print("Loaded level:", level_path)
        print("Loaded game objects:", len(objects))
        print(
            "Loaded enemies:",
            [(obj.name, obj.rect.topleft) for obj in objects if isinstance(obj, Enemy)],
        )

        return player, objects
